#[cfg(test)]
mod tests {
    #[test]
    fn keeps_the_original_characters_in_order() {
        let zalgo = super::zalgify("hi!");
        let base: String = zalgo.chars().filter(|ch| !('\u{0300}'..='\u{036f}').contains(ch)).collect();
        assert_eq!(base, "hi!");
        assert!(zalgo.chars().count() >= 3 * 3);
    }
}
